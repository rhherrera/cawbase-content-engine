"""Build outputs/results-summary.md (every check, macOS | Linux side by side) from the two results files."""

import json
from pathlib import Path

R = {e: json.loads(Path(f"outputs/results-{e}.json").read_text()) for e in ("macos", "linux")}
keyf = lambda r: (r["exp"], r["subject"], r["check"])  # noqa: E731
idx = {e: {} for e in R}
for e, d in R.items():
    for r in d["rows"]:
        idx[e].setdefault(keyf(r), []).append(r)
keys = sorted(set(k for e in idx for k in idx[e]))
sym = {"pass": "pass", "fail": "FAIL", "limitation": "limitation", "pending": "pending", "info": "info"}
out = [
    "# A04 — results of every check (generated by `make_summary.py` from `results-macos.json` and `results-linux.json`)",
    "",
    f"macOS: revision `{R['macos']['env']['git_rev'][:9]}`, code tree dirty = {R['macos']['env']['code_tree_dirty']}; Linux (Docker): revision `{R['linux']['env']['git_rev'][:9]}`, dirty = {R['linux']['env']['code_tree_dirty']}.",
    "Status per environment; `-` = the check does not exist in that environment (e.g. DOCX renders need LibreOffice, Linux only).",
    "",
    "| Exp | Subject | Check | macOS | Linux |",
    "|---|---|---|---|---|",
]
for k in keys:
    cells = []
    for e in ("macos", "linux"):
        rs = idx[e].get(k)
        cells.append(", ".join(sorted({sym[r["status"]] for r in rs})) if rs else "-")
    out.append(f"| {k[0]} | {k[1]} | {k[2].replace('|', '/')} | {cells[0]} | {cells[1]} |")
Path("outputs/results-summary.md").write_text("\n".join(out) + "\n")
tot = {e: {s: sum(1 for r in d["rows"] if r["status"] == s) for s in sym} for e, d in R.items()}
print(json.dumps(tot))
by = {}
for e, d in R.items():
    for r in d["rows"]:
        by.setdefault((r["exp"], e), {}).setdefault(r["status"], 0)
        by[(r["exp"], e)][r["status"]] += 1
for k in sorted(by):
    print(k, by[k])
