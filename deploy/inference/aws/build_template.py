#!/usr/bin/env python3
"""Generate cloudformation.yaml: embed a deterministic tar.gz (base64) of the host-side files into the user data.

    python3 deploy/inference/aws/build_template.py           # write cloudformation.yaml
    python3 deploy/inference/aws/build_template.py --check   # exit 1 if cloudformation.yaml is stale
    python3 deploy/inference/aws/build_template.py --report  # target, volume minimum and user data size

Bundled: manifest.json reduced to the AWS target model (generated from the full manifest: same id, file, URL, size
and SHA-256), server/ (scripts, units, profiles), aws/bootstrap.sh, bench/host-facts.sh, bench/boot-timings.sh and
bench/mem-sample.sh. In the bundled shell scripts the documentation header (the comment block right after the
shebang) is replaced by a pointer to the file in the repository; the code is unchanged. The AWS target comes from
manifest.json (`targets.aws` and `aws`): instance type, model id, file and the minimum weights volume, computed
from the exact artifact size. EC2 limits raw
user data to 16 KiB: the build renders the user data script with the bundle and the longest values the parameters
allow, and fails if it would exceed the limit.
"""

from __future__ import annotations

import base64
import gzip
import io
import json
import math
import re
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent  # deploy/inference
FILES = [
    "manifest.json",
    "aws/bootstrap.sh",
    "bench/host-facts.sh",
    "bench/boot-timings.sh",
    "bench/mem-sample.sh",
] + sorted(str(p.relative_to(ROOT)) for p in (ROOT / "server").rglob("*") if p.is_file() and p.suffix != ".example")
USER_DATA_LIMIT = 16 * 1024
GIB = 1024**3
# ext4 metadata (inode tables, journal) take a few percent of the volume (formatted with -m 0: no root reserve);
# one copy of the model at a time (install-model.sh removes an unverifiable file before downloading again)
FS_USABLE_FRACTION = 0.95
HEADROOM_GIB = 1
WEIGHTS_DEFAULT_GIB = 40
# worst-case lengths of the values CloudFormation substitutes in the user data (see the template constraints)
WORST_CASE = {
    "WeightsVolume": "vol-" + "f" * 17,
    "AWS::Region": "x" * 20,  # longest region names today: 14
    "ApiKeyParameterName": "/" + "x" * 255,
    "ServerProfile": "x" * 40,
    "GuardIdleMinutes": "1440",
}


def aws_target() -> dict[str, str | int]:
    m = json.loads((ROOT / "manifest.json").read_text(encoding="utf-8"))
    model_id = m["targets"]["aws"]
    model = m["models"][model_id]
    model_gib = model["bytes"] / GIB
    min_gib = math.ceil(model_gib / FS_USABLE_FRACTION + HEADROOM_GIB)
    return {
        "__INSTANCE_TYPE__": m["aws"]["instance_type"],
        "__GPU__": m["aws"]["gpu"].split(",")[0],
        "__MODEL_ID__": model_id,
        "__QUANT__": model["quantization"],
        "__MODEL_FILE__": model["file"],
        "__MODEL_GIB__": f"{model_gib:.2f}",
        "__WEIGHTS_MIN_GIB__": min_gib,
        "__WEIGHTS_DEFAULT_GIB__": max(WEIGHTS_DEFAULT_GIB, min_gib),
    }


def user_data_size(rendered: str, b64: str) -> int:
    """Raw size of the user data script after CloudFormation's substitutions, with worst-case parameter values."""
    block = rendered.split("Fn::Base64: !Sub", 1)[1].split("- Bundle:", 1)[0]
    lines = block.split("\n")[2:]  # after "- |"
    indent = min(len(x) - len(x.lstrip()) for x in lines if x.strip())
    script = "\n".join(x[indent:] for x in lines).rstrip() + "\n"
    script = script.replace("${Bundle}", b64)
    for key, value in WORST_CASE.items():
        script = script.replace("${" + key + "}", value)
    if re.search(r"\$\{[^}]+\}", script):
        raise SystemExit(f"unexpected substitution in the user data: {re.findall(r'[$][{][^}]+[}]', script)}")
    return len(script.encode())


HOST_MODEL_KEYS = ("alias", "quantization", "repository", "revision", "file", "url", "bytes", "sha256")


def host_manifest() -> bytes:
    """The manifest the AWS host receives: only its target model (user data is limited to 16 KiB)."""
    m = json.loads((ROOT / "manifest.json").read_text(encoding="utf-8"))
    model_id = m["targets"]["aws"]
    model = {k: m["models"][model_id][k] for k in HOST_MODEL_KEYS}
    host = {
        "manifest_version": m["manifest_version"],
        "note": "generated by aws/build_template.py from manifest.json: AWS target only",
        "models": {model_id: model},
        "targets": {"aws": model_id},
    }
    return (json.dumps(host, indent=1) + "\n").encode()


def host_script(rel: str, data: bytes) -> bytes:
    """A bundled shell script without its documentation header (comment lines right after the shebang)."""
    lines = data.decode().split("\n")
    if not lines[0].startswith("#!"):
        return data
    i = 1
    while i < len(lines) and lines[i].startswith("#") and not lines[i].startswith("# shellcheck"):
        i += 1
    pointer = f"# deploy/inference/{rel} in the repository documents this script (header not bundled)"
    return "\n".join([lines[0], pointer, *lines[i:]]).encode()


def bundle() -> str:
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w", format=tarfile.USTAR_FORMAT) as tar:
        for rel in FILES:
            data = host_manifest() if rel == "manifest.json" else (ROOT / rel).read_bytes()
            if rel.endswith(".sh"):
                data = host_script(rel, data)
            info = tarfile.TarInfo(rel)
            info.size, info.mtime, info.uid, info.gid = len(data), 0, 0, 0
            info.mode = 0o755 if rel.endswith(".sh") else 0o644
            tar.addfile(info, io.BytesIO(data))
    gz = io.BytesIO()
    with gzip.GzipFile(fileobj=gz, mode="wb", mtime=0, compresslevel=9) as f:
        f.write(raw.getvalue())
    return base64.b64encode(gz.getvalue()).decode()


def render() -> str:
    tpl = (ROOT / "aws" / "cloudformation.template.yaml").read_text(encoding="utf-8")
    for key, value in aws_target().items():
        tpl = tpl.replace(key, str(value))
    b64 = bundle()
    size = user_data_size(tpl, b64)
    if size > USER_DATA_LIMIT:
        raise SystemExit(f"user data too large: {size} bytes > {USER_DATA_LIMIT} (bundle {len(b64)} bytes)")
    leftover = re.findall(r"__[A-Z_]+__", tpl.replace("__BUNDLE_B64__", ""))
    if leftover:
        raise SystemExit(f"unreplaced placeholders: {leftover}")
    out = tpl.replace("__BUNDLE_B64__", b64)
    return out.replace("GENERATED by build_template.py from", "GENERATED (do not edit) by build_template.py from")


def report() -> dict[str, int | str]:
    tpl = (ROOT / "aws" / "cloudformation.template.yaml").read_text(encoding="utf-8")
    target = aws_target()
    for key, value in target.items():
        tpl = tpl.replace(key, str(value))
    b64 = bundle()
    size = user_data_size(tpl, b64)
    return {
        "instance_type": str(target["__INSTANCE_TYPE__"]),
        "model": str(target["__MODEL_ID__"]),
        "weights_min_gib": int(target["__WEIGHTS_MIN_GIB__"]),
        "weights_default_gib": int(target["__WEIGHTS_DEFAULT_GIB__"]),
        "bundle_b64_bytes": len(b64),
        "user_data_worst_case_bytes": size,
        "user_data_limit_bytes": USER_DATA_LIMIT,
        "template_bytes": len(render().encode()),
    }


def main() -> int:
    target = ROOT / "aws" / "cloudformation.yaml"
    text = render()
    if "--report" in sys.argv:
        print(json.dumps(report(), indent=2))
        return 0
    if "--check" in sys.argv:
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            print("cloudformation.yaml is stale; run build_template.py", file=sys.stderr)
            return 1
        print("cloudformation.yaml is up to date")
        return 0
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT.parent.parent)} ({len(bundle())} bytes of bundle)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
